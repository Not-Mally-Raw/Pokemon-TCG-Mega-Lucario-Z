    "    \n",
    "    # [FIX P1] Convert strings to explicit enums safely\n",
    "    opt_type_str = _enum_to_string(_safe_get(raw_option, 'type', ''))\n",
    "    try: opt.option_type = OptionType(opt_type_str)\n",
