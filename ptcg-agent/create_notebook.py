    "        \n",
    "    opt.index = _safe_int(_safe_get(raw_option, 'index', 0))\n",
    "    opt.player_index = _safe_int(_safe_get(raw_option, 'playerIndex', 0))\n",
    "    opt.number = _safe_int(_safe_get(raw_option, 'number', 0))\n",
    "    return opt\n",
