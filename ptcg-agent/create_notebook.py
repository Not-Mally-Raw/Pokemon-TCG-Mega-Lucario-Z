    "        \n",
    "    sel.min_count = _safe_int(_safe_get(raw_select, 'minCount', 1), 1)\n",
    "    sel.max_count = _safe_int(_safe_get(raw_select, 'maxCount', 1), 1)\n",
    "    return sel\n",
